"""reports/dataset_stats.md — distributions, lengths, CMI, label balance, fairness slices, IAA."""

from __future__ import annotations

import json
import statistics
from collections import Counter
from pathlib import Path

from lexvaani.export.release import NAME


def _read(p: Path):
    with open(p, encoding="utf-8") as f:
        return [json.loads(l) for l in f if l.strip()]


def _table(title: str, counter: Counter, total: int | None = None) -> list[str]:
    total = total or sum(counter.values())
    out = [f"### {title}", "", "| value | count | % |", "|---|---|---|"]
    for k, v in sorted(counter.items(), key=lambda x: (-x[1], str(x[0]))):
        out.append(f"| {k} | {v} | {100 * v / total:.1f} |")
    return out + [""]


def write_stats(root: Path) -> None:
    rel = root / "release" / NAME
    narr = []
    for sp in ("train", "dev", "test"):
        for r in _read(rel / "narratives" / f"{sp}.jsonl"):
            r["_split"] = sp
            narr.append(r)
    asr = [r for sp in ("train", "dev", "test") for r in _read(rel / "narratives_asr" / f"{sp}.jsonl")]
    dlg = [r for sp in ("train", "dev", "test") for r in _read(rel / "dialogues" / f"{sp}.jsonl")]
    specs = [r for sp in ("train", "dev", "test") for r in _read(rel / "specs" / f"{sp}.jsonl")]
    info = json.loads((rel / "release_info.json").read_text())
    L = ["# LexVaani-IN dataset statistics (v0.1)", "", "Generated by `make stats` from the release files.", "",
         "## Size", "",
         f"- Scenario specs: **{len(specs)}** (base + minimal-pair siblings; {len(info['dropped_duplicate_specs'])} duplicate specs removed at export)",
         f"- Clean narratives: **{len(narr)}** · ASR-noisy narratives: **{len(asr)}** · dialogues: **{len(dlg)}**",
         f"- Dialogue turns: **{sum(len(d['turns']) for d in dlg)}** · oracle decision points: **{sum(len(d['decision_points']) for d in dlg)}**",
         f"- Explanation references: **{sum(info['counts'][f'explanations/{s}'] for s in ('train', 'dev', 'test'))}**", "",
         "## Splits (clean narratives)", ""]
    L += _table("split", Counter(r["_split"] for r in narr))
    L += ["## Distributions (clean narratives)", ""]
    L += _table("domain (multi-issue samples count once per domain)", Counter(d for r in narr for d in r["annotations"]["domains"] or ["(none: out-of-scope / non-legal)"]))
    L += _table("issue (multi-label)", Counter(i for r in narr for i in r["annotations"]["issues"]))
    L += _table("language / script variant", Counter(r["lang_variant"] for r in narr))
    L += _table("variation", Counter(r["variation"] for r in narr))
    L += _table("difficulty", Counter(r["difficulty"] for r in narr))
    L += ["## Lengths", "", "| variant | mean chars | median chars | mean tokens | max tokens |", "|---|---|---|---|---|"]
    by_v: dict[str, list] = {}
    for r in narr:
        by_v.setdefault(r["lang_variant"], []).append(r["text"])
    for v, ts in sorted(by_v.items()):
        ch = [len(t) for t in ts]
        tok = [len(t.split()) for t in ts]
        L.append(f"| {v} | {statistics.mean(ch):.0f} | {statistics.median(ch):.0f} | {statistics.mean(tok):.1f} | {max(tok)} |")
    dl = [len(d["turns"]) for d in dlg]
    L += ["", f"Dialogues: mean {statistics.mean(dl):.1f} turns (max {max(dl)}).", "",
          "## Code-Mixing Index", "", "![CMI histogram](figures/cmi_histogram.png)", ""]
    qc = json.loads((root / "reports" / "qc_results.json").read_text())
    L += ["| variant | mean | median | min | max |", "|---|---|---|---|---|"]
    L += [f"| {k} | {v['mean']} | {v['median']} | {v['min']} | {v['max']} |" for k, v in qc["cmi"].items()]
    L += ["", "## Label balance", ""]
    L += _table("T6 epistemic status (facts)", Counter(f["status"] for r in narr for f in r["annotations"]["facts"]))
    L += _table("T6 hedged facts", Counter(f["hedged"] for r in narr for f in r["annotations"]["facts"]))
    L += _table("T7 element values (narrative-level)", Counter(e["value"] for r in narr for e in r["annotations"]["elements"]))
    L += _table("T2 entity types", Counter(m["type"] for r in narr for m in r["annotations"]["entities"]))
    L += _table("T2 mention kinds", Counter(m["kind"] for r in narr for m in r["annotations"]["entities"]))
    L += _table("T3 events: negated / hypothetical / asserted",
                Counter("negated" if e["negated"] else "hypothetical" if e["hypothetical"] else "asserted"
                        for r in narr for e in r["annotations"]["events"]))
    L += _table("T4 TIMEX types", Counter(t["type"] for r in narr for t in r["annotations"]["timexes"]))
    L += _table("T4 TLINK relations", Counter(t["relation"] for r in narr for t in r["annotations"]["tlinks"]))
    L += _table("T12 clarification labels", Counter(t["clarification"] for d in dlg for t in d["turns"] if t.get("clarification")))
    L += _table("T13 triage", Counter(r["annotations"]["triage"] for r in narr))
    L += _table("T13 risk flags", Counter(f for r in narr for f in r["annotations"]["risk_flags"]) or Counter({"(none)": 1}))
    L += _table("minimal-pair flip types (specs)", Counter(s["minimal_pair"]["flip_type"] for s in specs if s.get("minimal_pair")))
    L += _table("law regime (specs with criminal-law routing)", Counter(s["law_regime"] for s in specs if s.get("law_regime")))
    L += ["## Fairness slices (clean narratives)", "",
          "Slice variables are sampled independently of narrative style (no stereotyped language is tied to them).", ""]
    for k in ("gender", "age_group", "settlement", "region", "religion", "literacy_proxy"):
        L += _table(f"speaker {k}", Counter(r["metadata"][k] for r in narr))
    L += ["## Inter-annotator agreement", "",
          "**Not yet available.** The double-annotation subset (≥15% of narratives, two annotators each) is exported to "
          "`annotation/labelstudio/tasks_double.json`. Agreement (Cohen's/Fleiss' κ for categorical labels, span-F1 for "
          "spans, graph-F1 for Case Graphs) will be computed with `python -m lexvaani.annotation.iaa` and reported here. "
          "No numbers are estimated in advance.", ""]
    (root / "reports" / "dataset_stats.md").write_text("\n".join(L), encoding="utf-8")
    print("stats: reports/dataset_stats.md")
